// TestDefaultOptions verifies the default node options and the default values loaded from the
// environment are applied.
func TestDefaultOptions(t *testing.T) {
	o := defaultOptions()

	if o.ctx == nil {
		t.Fatal("ctx should not be nil")
	}
	if o.id == "" {
		t.Fatal("id should be generated by default")
	}
	if o.name != defaultName {
		t.Fatalf("expect name %q, got %q", defaultName, o.name)
	}
	if o.codec == nil || o.codec.Name() != defaultCodec {
		t.Fatalf("expect default codec %q, got %v", defaultCodec, o.codec)
	}
	if o.weight != defaultWeight {
		t.Fatalf("expect weight %d, got %d", defaultWeight, o.weight)
	}
	if o.addr != defaultAddr {
		t.Fatalf("expect addr %q, got %q", defaultAddr, o.addr)
	}
	if o.taskQueueSize != defaultTaskQueueSize {
		t.Fatalf("expect task queue size %d, got %d", defaultTaskQueueSize, o.taskQueueSize)
	}
	if o.messageQueueSize != defaultMessageQueueSize {
		t.Fatalf("expect message queue size %d, got %d", defaultMessageQueueSize, o.messageQueueSize)
	}
	if o.linker == nil {
		t.Fatal("linker options should not be nil")
	}
	if o.linker.connNum != defaultLinkerConnNum {
		t.Fatalf("expect conn num %d, got %d", defaultLinkerConnNum, o.linker.connNum)
	}
	if o.linker.callTimeout != time.Duration(3)*time.Second {
		t.Fatalf("expect call timeout 3s, got %v", o.linker.callTimeout)
	}
	if o.linker.dialTimeout != time.Duration(3)*time.Second {
		t.Fatalf("expect dial timeout 3s, got %v", o.linker.dialTimeout)
	}
	if o.linker.dialRetryTimes != defaultLinkerDialRetryTimes {
		t.Fatalf("expect dial retry times %d, got %d", defaultLinkerDialRetryTimes, o.linker.dialRetryTimes)
	}
	if o.linker.faultRecoveryTime != time.Duration(5)*time.Second {
		t.Fatalf("expect fault recovery time 5s, got %v", o.linker.faultRecoveryTime)
	}
	if o.linker.commandQueueSize != defaultLinkerCommandQueueSize {
		t.Fatalf("expect command queue size %d, got %d", defaultLinkerCommandQueueSize, o.linker.commandQueueSize)
	}
}

