// TestNodeOptionsApplyOnNewNode verifies that the With* options are applied by NewNode.
func TestNodeOptionsApplyOnNewNode(t *testing.T) {
	n := NewNode(
		WithID("id"),
		WithName("name"),
		WithAddr("127.0.0.1:0"),
		WithExpose(true),
		WithWeight(3),
		WithTaskQueueSize(16),
		WithMessageQueueSize(32),
		WithRegistry(&stubRegistry{}),
		WithLocator(&stubLocator{}),
	)

	if n.opts.id != "id" || n.opts.name != "name" || !n.opts.expose || n.opts.weight != 3 {
		t.Fatalf("options not applied: %+v", n.opts)
	}
	if n.opts.taskQueueSize != 16 || n.opts.messageQueueSize != 32 {
		t.Fatalf("queue sizes not applied: %+v", n.opts)
	}
}

// TestDefaultActorOptions verifies the default actor options.
func TestDefaultActorOptions(t *testing.T) {
	o := defaultActorOptions()

	if !o.wait {
		t.Fatal("wait should default to true")
	}
	if !o.dispatch {
		t.Fatal("dispatch should default to true")
	}
	if o.taskQueueSize != 1024 {
		t.Fatalf("expect task queue size 1024, got %d", o.taskQueueSize)
	}
	if o.messageQueueSize != 2048 {
		t.Fatalf("expect message queue size 2048, got %d", o.messageQueueSize)
	}
	if o.taskWriteTimeout != 3*time.Second {
		t.Fatalf("expect task write timeout 3s, got %v", o.taskWriteTimeout)
	}
	if o.messageWriteTimeout != 3*time.Second {
		t.Fatalf("expect message write timeout 3s, got %v", o.messageWriteTimeout)
	}
}

// TestActorOptions verifies every actor option.
func TestActorOptions(t *testing.T) {
	o := defaultActorOptions()

	WithActorID("id")(o)
	WithActorKind("kind")(o)
	WithActorArgs(1, "a")(o)
	WithActorArgs(true)(o)
	WithActorNonWait()(o)
	WithActorNonDispatch()(o)
	WithActorTaskQueueSize(8)(o)
	WithActorTaskWriteTimeout(time.Second)(o)
	WithActorMessageQueueSize(16)(o)
	WithActorMessageWriteTimeout(time.Second)(o)

	if o.id != "id" || o.kind != "kind" {
		t.Fatalf("id/kind not applied: %+v", o)
	}
	if len(o.args) != 3 {
		t.Fatalf("expect 3 args, got %d", len(o.args))
	}
	if o.wait {
		t.Fatal("wait should be false")
	}
	if o.dispatch {
		t.Fatal("dispatch should be false")
	}
	if o.taskQueueSize != 8 || o.messageQueueSize != 16 {
		t.Fatalf("queue sizes not applied: %+v", o)
	}
	if o.taskWriteTimeout != time.Second || o.messageWriteTimeout != time.Second {
		t.Fatalf("write timeouts not applied: %+v", o)
	}
}
